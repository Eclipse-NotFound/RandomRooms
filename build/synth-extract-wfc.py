# -*- coding: utf-8 -*-
"""v3.6 数据导出：从原版语料提取 48x4 条带库 + 马尔可夫转移表 → RRStripData.as

- 条带: 原版房间按 4 行切条（6 条/房），取高频子集（~80% 覆盖）
- 转移: (上条带 -> 下条带) 出现次数（修剪后的重计数）
- 带型: 每条带 4 行中墙占比>0.5 的行位掩码（供类型引导）
输出: mods/RandomRooms/src/rr/RRStripData.as
"""
import xml.etree.ElementTree as ET
import glob, os
from collections import Counter, defaultdict

ROOMS = r"C:\Program Files (x86)\Steam\steamapps\common\Remains\Rooms"
OUT = r"C:\Program Files (x86)\Steam\steamapps\common\Remains\mods\RandomRooms\src\rr\RRStripData.as"
TIP = {"beg0","beg","beg1","end","end1","pass","passroof","roofpass","vert","surf","roof","back","uniq"}
BLAND = {"stable": "stable", "sewer": "sewer", "mane": "mane", "plant": "plant"}
WALL = set("ABCDEFGHIJKLMNOPQRST")
MAX_STRIPS = {"stable": 150, "sewer": 110, "plant": 190, "mane": 130}

strip_lib = defaultdict(Counter)
trans = defaultdict(Counter)
for fn in sorted(glob.glob(os.path.join(ROOMS, "rooms_*.xml"))):
    land = os.path.basename(fn).replace("rooms_", "").replace(".xml", "")
    biome = BLAND.get(land)
    if biome is None:
        continue
    tree = ET.parse(fn)
    for room in tree.getroot().findall("room"):
        o = room.find("options")
        tip = o.get("tip", "") if o is not None else ""
        if tip in TIP:
            continue
        g = [a.text.split(".") for a in room.findall("a")]
        if len(g) != 25 or any(len(r) != 48 for r in g):
            continue
        strips = [tuple("|".join(g[r*4+dy]) for dy in range(4)) for r in range(6)]
        for s in strips:
            strip_lib[biome][s] += 1
        for i in range(5):
            trans[biome][(strips[i], strips[i+1])] += 1

def wallband(s):
    """条带 4 行中墙占比>0.5 的行位掩码（位0=顶行）"""
    rows = s if isinstance(s, tuple) else s.split("|")
    m = 0
    for i, r in enumerate(rows):
        if sum(1 for c in r if c and c[0] in WALL) / 48 > 0.5:
            m |= 1 << i
    return m

lines = []
lines.append("// Auto-generated by build/synth-extract-wfc.py from original corpus rooms")
lines.append("// 48x4 条带库 + 马尔可夫转移表（v3.6 原版条带合成）")
lines.append("package rr")
lines.append("{")
lines.append("   public class RRStripData")
lines.append("   {")
lines.append("      public static const BIOMES:Array = [\"stable\",\"sewer\",\"plant\",\"mane\"];")
for biome in BLAND.values():
    top = strip_lib[biome].most_common(MAX_STRIPS[biome])
    idx = {s: i for i, (s, _) in enumerate(top)}
    # 重计数转移（仅保留库内条带）
    tc = Counter()
    for (a, b), c in trans[biome].items():
        if a in idx and b in idx:
            tc[(idx[a], idx[b])] += c
    weights = ",".join(str(f) for _, f in top)
    bands = ",".join(str(wallband(s)) for s, _ in top)
    strips_txt = "~".join("|".join(s) for s, _ in top)
    # 转移表: "i:j1,c1;j2,c2;...;"
    t_parts = []
    for (ia, ib), c in sorted(tc.items()):
        t_parts.append(f"{ia}:{ib},{c}")
    trans_txt = ";".join(t_parts)
    lines.append(f"      public static const S_{biome.upper()}:String = \"{strips_txt}\";")
    lines.append(f"      public static const W_{biome.upper()}:String = \"{weights}\";")
    lines.append(f"      public static const B_{biome.upper()}:String = \"{bands}\";")
    lines.append(f"      public static const T_{biome.upper()}:String = \"{trans_txt}\";")
    print(f"{biome}: 条带{len(top)} 转移{len(tc)}")
lines.append("   }")
lines.append("}")
open(OUT, "w", encoding="utf-8").write("\n".join(lines))
sz = os.path.getsize(OUT)
print("输出:", OUT, f"{sz/1024:.1f} KB")
